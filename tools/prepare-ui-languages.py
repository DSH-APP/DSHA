#!/usr/bin/env python3
"""Generate bounded native UI dictionaries; never translate user content at runtime."""
from source_text import write_text as write_source_text, matches_text
import argparse,json
from pathlib import Path
from ui_language_catalog import LANGUAGES, load_catalog, format_signature

def generate(root,output):
    messages,catalogs=load_catalog(root)
    formats=sorted((item for item in messages if item.get('uiFormat')),
                   key=lambda item:max(len(item['zh'].replace('%s','')),len(item['en'].replace('%s',''))),reverse=True)
    folder=output/'com/deepseekharness/app/util';folder.mkdir(parents=True,exist_ok=True)
    def write(name,lines):
        target=folder/(name+'.java');value='\n'.join(lines)+'\n'
        if not matches_text(target,value,encoding='utf-8'):write_source_text(target,value,encoding='utf-8')
    # One class per language bounds both JVM constant pools and method bytecode size.
    classes={tag:'UiMessages_'+tag.replace('-','_') for tag in LANGUAGES}
    for tag in LANGUAGES:
        name=classes[tag];data=catalogs[tag]
        lines=['package com.deepseekharness.app.util;','import java.util.*;',
               '/** Generated by tools/prepare-ui-languages.py. */',f'final class {name} {{',
               'static final Map<String,String> VALUES = build();',
               'private static Map<String,String> build() { Map<String,String> values=new HashMap<>();']
        for i in range(0,len(messages),80):lines.append(f'part{i//80}(values);')
        lines+=['return Collections.unmodifiableMap(values);','}']
        for i in range(0,len(messages),80):
            lines.append(f'private static void part{i//80}(Map<String,String> values) {{')
            for item in messages[i:i+80]:
                lines.append('values.put('+json.dumps(item['zh'],ensure_ascii=False)+','+json.dumps(data[item['id']],ensure_ascii=False)+');')
            lines.append('}')
        lines.append('static final String[] FORMATS = new String[] {')
        lines += [json.dumps(data[item['id']],ensure_ascii=False)+',' for item in formats]
        lines+=['};','}'];write(name,lines)
    lines=['package com.deepseekharness.app.util;','import java.util.*;',
           '/** Generated by tools/prepare-ui-languages.py. */','final class UiMessages {',
           'static final Map<String,String> EN = UiMessages_en.VALUES;',
           'static Map<String,String> forLanguage(String language) {',
           'if (language == null) throw new IllegalArgumentException("UI_LANGUAGE");',
           'switch(language) {']
    for tag in LANGUAGES:lines.append('case '+json.dumps(tag)+': return '+classes[tag]+'.VALUES;')
    lines+=['default: throw new IllegalArgumentException("UI_LANGUAGE");','}}',
            'static String[] formatsForLanguage(String language) {','switch(language) {']
    for tag in LANGUAGES:lines.append('case '+json.dumps(tag)+': return '+classes[tag]+'.FORMATS;')
    lines+=['default: throw new IllegalArgumentException("UI_LANGUAGE");','}}',
            'static final String[][] FORMATS = legacyFormats();',
            'private static String[][] legacyFormats() {',
            'String[] zh = UiMessages_zh.FORMATS, en = UiMessages_en.FORMATS;',
            'String[][] pairs = new String[zh.length][2];',
            'for (int i=0;i<zh.length;i++) { pairs[i][0]=zh[i]; pairs[i][1]=en[i]; }',
            'return pairs;','}','}']
    write('UiMessages',lines)
    print(f'UI language catalog: {len(messages)} entries x {len(LANGUAGES)} languages')

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]);parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args();generate(args.root,args.output)
